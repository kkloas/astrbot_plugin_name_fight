export function newMoveFor(event) {
    return newMartialScores[event?.martialArtId || '']?.[event?.move || ''];
}
export function newMartialMotion(event, time, travel) {
    const definition = newMoveFor(event);
    if (!definition)
        return undefined;
    const keys = definition.keys;
    let k = keys[keys.length - 1];
    for (let i = 1; i < keys.length; i++)
        if (time < keys[i][0]) {
            const a = keys[i - 1], b = keys[i], f = ease((time - a[0]) / (b[0] - a[0]));
            k = a.map((value, j) => value + (b[j] - value) * f);
            break;
        }
    const [, progress, lift, height, lean, frontAngle, rearAngle, reach, blade, backX, frontX, footY] = k;
    const hip = [0, -height], neck = [lean, -height - Math.sqrt(52 * 52 - lean * lean)];
    const shoulders = [[neck[0] - 10, neck[1] + 6], [neck[0] + 10, neck[1] + 6]];
    const polar = (p, a, r) => [p[0] + Math.cos(a) * r, p[1] + Math.sin(a) * r];
    const freeReach = 58 + 14 * ease((time - 350) / 300) * (1 - ease((time - 1100) / 200));
    const [rearElbow, rearHand] = twoBone(shoulders[0], polar(shoulders[0], rearAngle, freeReach), 40, -1);
    const [elbow, hand] = twoBone(shoulders[1], polar(shoulders[1], frontAngle, reach), 40, 1);
    const [rearKnee, rearFoot] = twoBone(hip, [backX, footY], 48, -1);
    const [knee, foot] = twoBone(hip, [frontX, footY], 48, -1);
    const pose = { points: [[neck[0], neck[1] - 21], neck, hip, rearElbow, rearHand, elbow, hand, rearKnee, rearFoot, knee, foot], shoulders, sword: blade, lean: 0 };
    // Blade reach is part of contact placement; the body stops short of the target.
    const stopShort = event.martialArtId === 'sword_danyu' ? 33 : 42;
    return { pose, x: Math.max(0, travel - stopShort) * progress, lift, opacity: 1, blink: 0 };
}
